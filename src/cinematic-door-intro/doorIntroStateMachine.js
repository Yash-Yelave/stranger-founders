  [DOOR_INTRO_STATES.KEY_APPROACHING_LOCK]: [DOOR_INTRO_STATES.KEY_SNAPPING, DOOR_INTRO_STATES.UNLOCKING, DOOR_INTRO_STATES.DOOR_OPENING, DOOR_INTRO_STATES.KEY_PICKED, DOOR_INTRO_STATES.COMPLETE],
