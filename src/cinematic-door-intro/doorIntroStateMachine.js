  [DOOR_INTRO_STATES.BOXES_VISIBLE]: [DOOR_INTRO_STATES.SEARCHING, DOOR_INTRO_STATES.BOX_OPENING, DOOR_INTRO_STATES.DOOR_IDLE, DOOR_INTRO_STATES.COMPLETE],
  [DOOR_INTRO_STATES.SEARCHING]: [DOOR_INTRO_STATES.BOX_OPENING, DOOR_INTRO_STATES.DOOR_IDLE, DOOR_INTRO_STATES.COMPLETE],
